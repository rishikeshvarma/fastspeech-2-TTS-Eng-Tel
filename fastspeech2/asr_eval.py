"""[new] Intelligibility check with an ASR model (Whisper), not part of the reference.

    python fastspeech2/asr_eval.py English
    python fastspeech2/asr_eval.py Telugu --n 100

1. Transcribes Results/<language>/test_generated_audios/*.wav, so the report can say
   which words of each test sentence come out recognisably.
2. Takes --n validation utterances (never seen in training), synthesises each one from
   its ground-truth phone sequence with its own speaker, and transcribes both the
   synthesised audio and the real recording. The real recordings give the error rate
   that the ASR model itself makes on this speech; the gap to the synthesised audio is
   what the TTS model loses.

Writes Results/<language>/asr_eval.json. Needs `pip install transformers jiwer` and
downloads openai/whisper-large-v3-turbo (~1.6 GB) on first use.
"""

import argparse
import json
import os
import random
import re
import sys
import unicodedata
from pathlib import Path

import jiwer
import librosa
import numpy as np
import torch
from transformers import pipeline

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "fastspeech2"))

from configuration import load_config  # noqa: E402
from synthesis import synthesize_phones  # noqa: E402
from utils.model import get_model, get_vocoder, load_checkpoint  # noqa: E402

ASR_MODEL = "openai/whisper-large-v3-turbo"
ASR_RATE = 16000


def telugu_normalize(text):
    # Whisper's own basic normaliser replaces every combining mark with a space, which
    # destroys Telugu vowel signs; only punctuation and symbols are removed here
    text = unicodedata.normalize("NFC", text)
    text = "".join(" " if unicodedata.category(c)[0] in "PS" else c for c in text)
    return re.sub(r"\s+", " ", text).strip()


def load_audio(path):
    wav, _ = librosa.load(path, sr=ASR_RATE)
    return wav


def to_asr_rate(wav, sr):
    return librosa.resample(wav.astype(np.float32) / 32768.0, orig_sr=sr, target_sr=ASR_RATE)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("language", choices=["English", "Telugu"])
    parser.add_argument("--checkpoint", default="final")
    parser.add_argument("--n", type=int, default=100, help="validation utterances to score")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    configs = load_config(str(ROOT / args.language / "config.yaml"))
    preprocess_config, model_config, train_config = configs
    meta = preprocess_config["path"]["metadata_path"]
    results_dir = train_config["path"]["result_path"]
    sr = preprocess_config["preprocessing"]["audio"]["sampling_rate"]

    asr = pipeline("automatic-speech-recognition", model=ASR_MODEL, device=device,
                   dtype=torch.float16 if device.type == "cuda" else torch.float32)
    language = args.language.lower()
    norm = asr.tokenizer.normalize if language == "english" else telugu_normalize

    def transcribe(wavs):
        out = asr([{"raw": w, "sampling_rate": ASR_RATE} for w in wavs], batch_size=16,
                  generate_kwargs={"language": language, "task": "transcribe"})
        return [o["text"].strip() for o in out]

    report = {"asr_model": ASR_MODEL, "checkpoint": args.checkpoint}

    # 1. the test sentences, as generated by inference.py
    audio_dir = os.path.join(results_dir, "test_generated_audios")
    ids = sorted(f[:-4] for f in os.listdir(audio_dir) if f.endswith(".wav"))
    hyps = transcribe([load_audio(os.path.join(audio_dir, i + ".wav")) for i in ids])
    report["test_sentences"] = {}
    for i, h in zip(ids, hyps):
        with open(os.path.join(results_dir, "variance_adaptor_plots", i + ".json"), encoding="utf-8") as f:
            text = json.load(f)["text"]
        report["test_sentences"][i] = {"text": text, "asr": h}
        print("{}: {}\n     heard: {}".format(i, text, h))

    # 2. held-out validation utterances: real recording vs. synthesis of the same text
    with open(os.path.join(meta, "speakers.json")) as f:
        speakers = json.load(f)
    with open(os.path.join(meta, "val.txt"), encoding="utf-8") as f:
        val = [line.rstrip("\n").split("|") for line in f]
    val = [v for v in val if len(v[3].split()) >= 3]
    random.Random(args.seed).shuffle(val)
    val = val[: args.n]

    model = get_model(0, configs, device, train=False)
    ckpt = os.path.join(train_config["path"]["ckpt_path"], "{}.pth.tar".format(args.checkpoint))
    model.load_state_dict(load_checkpoint(ckpt, device)["model"])
    vocoder = get_vocoder(model_config, device)

    synth = []
    for basename, speaker, phones, text in val:
        words = [(text, phones.strip("{}").split())]
        result = synthesize_phones(model, vocoder, configs, words, speakers[speaker], device)
        synth.append(to_asr_rate(result["wav"], sr))
    refs = [norm(v[3]) for v in val]
    hyp_synth = [norm(h) for h in transcribe(synth)]
    scores = {"synthesised": {
        "wer": jiwer.wer(refs, hyp_synth), "cer": jiwer.cer(refs, hyp_synth)}}

    raw = preprocess_config["path"]["raw_path"]
    real_paths = [os.path.join(raw, v[1], v[0] + ".wav") for v in val]
    if all(os.path.exists(p) for p in real_paths):
        hyp_real = [norm(h) for h in transcribe([load_audio(p) for p in real_paths])]
        scores["real_recordings"] = {
            "wer": jiwer.wer(refs, hyp_real), "cer": jiwer.cer(refs, hyp_real)}
    report["validation"] = {"utterances": len(val), "seed": args.seed, **scores}
    report["validation_examples"] = [
        {"id": v[0], "reference": r, "synthesised": h}
        for v, r, h in list(zip(val, refs, hyp_synth))[:10]
    ]
    for name, s in scores.items():
        print("validation {:16s} WER {:.3f}  CER {:.3f}".format(name, s["wer"], s["cer"]))

    with open(os.path.join(results_dir, "asr_eval.json"), "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=1)
    print("Saved", os.path.join(results_dir, "asr_eval.json"))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
